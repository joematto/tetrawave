// TetraWave sorting grid: a translucent floating sheet holding every picture on the site.
// Columns are pages in book order (Part I · Section 1 …); rows are each page's picture index numbers
// (the same numbers shown in the corner of each picture). Shown by the header's "Grid" link (or #grid).
// Zoom: roll the mouse wheel forward/back over the grid (or pinch), the − / + buttons, the slider, or - and =.
// Pan: hold the mouse wheel (middle button) down and move the mouse.
// Move the sheet by its title bar; resize it from the bottom-right corner. Click a picture to see what it
// is; double-click it to open that page. Generated by build.py from the pages themselves.
(() => {
  const DATA = __DATA__;
  const css = `
#tw-grid { position: fixed; z-index: 2147483050; left: 40px; top: 90px; width: min(1100px, calc(100vw - 80px)); height: calc(100vh - 130px);
  display: flex; flex-direction: column; background: rgba(6,7,12,.84); outline: 1px solid rgba(245,202,151,.45);
  box-shadow: 0 8px 40px rgba(0,0,0,.6); resize: both; overflow: hidden; min-width: 320px; min-height: 220px;
  font: 400 12px/1.3 "Source Sans 3", Arial, sans-serif; color: #dcdcdc; }
#tw-grid .g-bar { flex: none; display: flex; align-items: center; gap: 10px; padding: 5px 8px; cursor: move; user-select: none;
  border-bottom: 1px solid rgba(245,202,151,.3); background: rgba(6,7,12,.6); }
#tw-grid .g-title { font: 600 11px/1 "Source Sans 3", Arial, sans-serif; letter-spacing: .1em; text-transform: uppercase; color: #f5ca97; margin-right: auto; }
#tw-grid button { font: 600 11px/1 "Source Sans 3", Arial, sans-serif; color: #f5ca97; background: none; border: 1px solid rgba(245,202,151,.45);
  padding: 4px 8px; cursor: pointer; }
#tw-grid button:hover { background: rgba(245,202,151,.12); }
#tw-grid input[type=range] { width: 140px; accent-color: #f5ca97; cursor: pointer; }
#tw-grid .g-zoom { min-width: 42px; text-align: right; color: #9a8f80; font: 600 11px/1 ui-monospace, Menlo, monospace; }
#tw-grid .g-view { flex: 1; overflow: auto; position: relative; }
#tw-grid .g-pad { display: inline-block; padding: 3000px; }
#tw-grid table { border-collapse: separate; border-spacing: 0; }
#tw-grid th { position: sticky; z-index: 2; background: rgba(12,13,20,.96); color: #f9e2ba; font-weight: 400; }
#tw-grid thead th { top: 0; padding: 4px 6px; border-bottom: 1px solid rgba(245,202,151,.35); border-right: 1px solid rgba(245,202,151,.12);
  width: var(--c); min-width: var(--c); max-width: var(--c); vertical-align: bottom; text-align: left; }
#tw-grid thead th .a, #tw-grid thead th .s { display: block; overflow: hidden; font: 600 10px/1.2 "Source Sans 3", Arial, sans-serif; letter-spacing: .06em; text-transform: uppercase; color: #f5ca97; white-space: nowrap; }
#tw-grid thead th .t { display: block; font: 400 10px/1.2 "Source Sans 3", Arial, sans-serif; color: #9a8f80; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }
#tw-grid thead th .s { display: none; font: 600 10px/1.2 "Source Sans 3", Arial, sans-serif; color: #f5ca97; text-align: center; }
#tw-grid.small thead th .a, #tw-grid.small thead th .t { display: none; }
#tw-grid.small thead th .s { display: block; }
#tw-grid.small thead th { padding: 3px 0; }
#tw-grid thead th a { color: inherit; text-decoration: none; display: block; }
#tw-grid thead th a:hover .a { text-decoration: underline; }
#tw-grid thead th.un { background: rgba(40,30,18,.96); border-left: 2px solid rgba(245,202,151,.6); }
#tw-grid th.corner { left: 0; z-index: 3; width: 34px; min-width: 34px; }
#tw-grid tbody th { left: 0; width: 34px; min-width: 34px; height: var(--c); padding: 0; text-align: center; font: 700 min(12px, calc(var(--c) * .7))/1 "Source Sans 3", Arial, sans-serif;
  border-right: 1px solid rgba(245,202,151,.35); border-bottom: 1px solid rgba(245,202,151,.12); }
#tw-grid td { width: var(--c); min-width: var(--c); max-width: var(--c); height: var(--c); padding: 0; line-height: 0; border-right: 1px solid rgba(245,202,151,.12); border-bottom: 1px solid rgba(245,202,151,.12); vertical-align: middle; text-align: center; }
#tw-grid td.un { border-left: 2px solid rgba(245,202,151,.6); background: rgba(245,202,151,.04); }
#tw-grid td .cell { position: relative; margin: auto; width: calc(var(--c) * .94); height: calc(var(--c) * .94); display: flex; align-items: center; justify-content: center; cursor: pointer; }
#tw-grid td img { max-width: 100%; max-height: 100%; object-fit: contain; display: block; }
#tw-grid td .cell.sel { outline: 2px solid #f5ca97; outline-offset: 1px; }
#tw-grid .g-info { flex: none; padding: 4px 8px; border-top: 1px solid rgba(245,202,151,.3); color: #cfc6b8; min-height: 16px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
#tw-grid .g-info b { color: #f5ca97; font-weight: 600; }`;
  const Z0 = 140, ZMIN = 12, ZMAX = 1400;
  const PAD = 3000;   // empty margin round the grid, so it can always be panned, however far you zoom out
  let el = null, size = Z0;
  const store = (k, v) => { try { localStorage.setItem('tw-grid-' + k, v); } catch (e) {} };
  const load = (k) => { try { return localStorage.getItem('tw-grid-' + k); } catch (e) { return null; } };

  function build() {
    const rows = Math.max(...DATA.map((p) => p.images.length));
    let h = '<table><thead><tr><th class="corner">#</th>';
    for (const p of DATA) {
      const lab = `<span class="a">${p.addr}</span><span class="t">${p.title}</span><span class="s">${p.short}</span>`;
      h += p.file ? `<th><a href="${p.file}" title="${p.addr} · ${p.title}">${lab}</a></th>` : `<th class="un" title="Pictures in the images folder that no page uses yet, and anything put in images/PENDING"><span>${lab}</span></th>`;
    }
    h += '</tr></thead><tbody>';
    for (let r = 0; r < rows; r++) {
      h += `<tr><th>${r + 1}</th>`;
      DATA.forEach((p, c) => {
        const im = p.images[r];
        const cls = p.file ? '' : ' class="un"';
        h += im ? `<td${cls}><div class="cell" data-c="${c}" data-r="${r}"><img src="${im.src}" alt="" loading="lazy" decoding="async"></div></td>` : `<td${cls}></td>`;
      });
      h += '</tr>';
    }
    return '<div class="g-pad">' + h + '</tbody></table></div>';
  }

  function setZoom(s, ax, ay) {
    const v = el.querySelector('.g-view'), old = size;
    size = Math.round(Math.max(ZMIN, Math.min(ZMAX, s)));
    // keep the point under the cursor (or the view's centre) in place while zooming
    const r = v.getBoundingClientRect();
    const px = (ax ?? r.left + r.width / 2) - r.left, py = (ay ?? r.top + r.height / 2) - r.top;
    const head = () => el.querySelector('thead').offsetHeight, side = () => el.querySelector('th.corner').offsetWidth;
    const h0 = head(), w0 = side();
    const fx = (v.scrollLeft + px - PAD - w0) / old, fy = (v.scrollTop + py - PAD - h0) / old;
    el.style.setProperty('--c', size + 'px'); el.classList.toggle('small', size < 100);
    v.scrollLeft = fx * size + PAD + side() - px; v.scrollTop = fy * size + PAD + head() - py;
    el.querySelector('input[type=range]').value = Math.log(size);
    el.querySelector('.g-zoom').textContent = Math.round(size / Z0 * 100) + '%';
    store('zoom', size);
  }
  function fit() {
    const v = el.querySelector('.g-view'), rows = Math.max(...DATA.map((p) => p.images.length));
    el.classList.add('small');
    const head = el.querySelector('thead').offsetHeight;
    const s = Math.floor(Math.min((v.clientWidth - 36) / DATA.length, (v.clientHeight - head - 4) / rows)) - 1;
    setZoom(s); v.scrollLeft = PAD; v.scrollTop = PAD;
  }

  function open() {
    if (el) return;
    const st = document.createElement('style'); st.id = 'tw-grid-css'; st.textContent = css; document.head.appendChild(st);
    el = document.createElement('div'); el.id = 'tw-grid'; el.tabIndex = -1;
    const pages = DATA.filter((p) => p.file), un = DATA.find((p) => !p.file);
    el.innerHTML = `<div class="g-bar"><span class="g-title">Sorting grid · ${pages.reduce((n, p) => n + p.images.length, 0)} pictures on ${pages.length} pages · ${un ? un.images.length : 0} unassigned</span>
      <button type="button" data-a="out" title="Zoom out (-)">−</button>
      <input type="range" min="${Math.log(ZMIN)}" max="${Math.log(ZMAX)}" step="0.01" aria-label="Zoom">
      <button type="button" data-a="in" title="Zoom in (=)">+</button><span class="g-zoom"></span>
      <button type="button" data-a="fit" title="Show every picture at once">Fit all</button>
      <button type="button" data-a="one" title="Back to the normal size">100%</button>
      <button type="button" data-a="close">Close</button></div>
      <div class="g-view">${build()}</div>
      <div class="g-info">Wheel forward/back to zoom · hold the wheel down and move to pan · click a picture to see what it is · double-click to open its page</div>`;
    document.body.appendChild(el);
    const pos = (load('pos') || '').split(',').map(Number);
    if (pos.length === 4 && pos.every(isFinite)) Object.assign(el.style, { left: pos[0] + 'px', top: pos[1] + 'px', width: pos[2] + 'px', height: pos[3] + 'px' });
    const v = el.querySelector('.g-view');
    setZoom(+load('zoom') || Z0);
    v.scrollLeft = PAD; v.scrollTop = PAD;

    el.addEventListener('click', (e) => {
      const a = e.target.closest('[data-a]')?.dataset.a;
      if (a === 'close') return hide();
      if (a === 'in') return setZoom(size * 1.25);
      if (a === 'out') return setZoom(size / 1.25);
      if (a === 'fit') return fit();
      if (a === 'one') { setZoom(Z0); const v = el.querySelector('.g-view'); v.scrollLeft = PAD; v.scrollTop = PAD; return; }
      const cell = e.target.closest('.cell');
      if (cell) {
        el.querySelectorAll('.cell.sel').forEach((c) => c.classList.remove('sel')); cell.classList.add('sel');
        const p = DATA[+cell.dataset.c], im = p.images[+cell.dataset.r];
        el.querySelector('.g-info').innerHTML = p.file
          ? `<b>${p.addr} · Picture ${+cell.dataset.r + 1}</b> · ${p.title} · ${im.file} · ${im.w} × ${im.h} px original`
          : `<b>Unassigned ${+cell.dataset.r + 1}</b> · ${im.file} · in images/${im.folder}` + (im.w ? ` · ${im.w} × ${im.h} px original` : '') + ' · not on any page yet';
      }
    });
    el.addEventListener('dblclick', (e) => { const cell = e.target.closest('.cell'); if (cell && DATA[+cell.dataset.c].file) location.href = DATA[+cell.dataset.c].file; });
    el.querySelector('input[type=range]').addEventListener('input', (e) => setZoom(Math.exp(+e.target.value)));
    // ArchiCAD-style: roll the mouse wheel forward to zoom in, back to zoom out (around the pointer);
    // hold the wheel (middle button) down and move the mouse to pan.
    v.addEventListener('wheel', (e) => {
      e.preventDefault();
      const dy = e.deltaMode === 1 ? e.deltaY * 33 : e.deltaMode === 2 ? e.deltaY * 400 : e.deltaY;
      setZoom(size * Math.exp(-dy * (e.ctrlKey ? 0.01 : 0.0018)), e.clientX, e.clientY);
    }, { passive: false });
    v.addEventListener('mousedown', (e) => {
      if (e.button !== 1) return;
      e.preventDefault();                                   // no browser auto-scroll
      const sx = e.clientX, sy = e.clientY, l = v.scrollLeft, t = v.scrollTop;
      v.style.cursor = 'grabbing';
      const mv = (m) => { v.scrollLeft = l - (m.clientX - sx); v.scrollTop = t - (m.clientY - sy); };
      const up = (u) => { if (u.button !== 1) return; removeEventListener('mousemove', mv); removeEventListener('mouseup', up); v.style.cursor = ''; };
      addEventListener('mousemove', mv); addEventListener('mouseup', up);
    });
    v.addEventListener('auxclick', (e) => { if (e.button === 1) e.preventDefault(); });   // middle-click doesn't open links
    el.addEventListener('keydown', (e) => {
      if (e.key === '=' || e.key === '+') { e.preventDefault(); setZoom(size * 1.25); }
      if (e.key === '-' || e.key === '_') { e.preventDefault(); setZoom(size / 1.25); }
      if (e.key === 'Escape') hide();
    });
    el.querySelector('.g-bar').addEventListener('pointerdown', (e) => {
      if (e.target.closest('button, input')) return;
      e.preventDefault();
      const r = el.getBoundingClientRect(), sx = e.clientX - r.left, sy = e.clientY - r.top;
      const mv = (m) => { el.style.left = (m.clientX - sx) + 'px'; el.style.top = Math.max(0, m.clientY - sy) + 'px'; };
      const up = () => { removeEventListener('pointermove', mv); removeEventListener('pointerup', up); savePos(); };
      addEventListener('pointermove', mv); addEventListener('pointerup', up);
    });
    new ResizeObserver(savePos).observe(el);
    el.focus({ preventScroll: true });
  }
  const savePos = () => { if (el) { const r = el.getBoundingClientRect(); store('pos', [r.left, r.top, r.width, r.height].map(Math.round).join(',')); } };
  function close() { if (el) { el.remove(); el = null; } const s = document.getElementById('tw-grid-css'); if (s) s.remove(); }
  function hide() { if (location.hash === '#grid') history.replaceState(null, '', location.pathname + location.search); close(); }
  addEventListener('hashchange', () => { if (location.hash === '#grid') open(); });
  if (location.hash === '#grid') open();
  document.querySelectorAll('[data-grid-toggle]').forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault();
    const toc = document.getElementById('toc'); if (toc) toc.hidden = true;
    if (el) hide(); else { history.replaceState(null, '', '#grid'); open(); }
  }));
})();
